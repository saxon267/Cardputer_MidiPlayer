# -*- coding: utf-8 -*-
"""Rasterise Silkscreen 8 px into 1-bit glyph cells for the firmware.

Cell: 6x8 px, one byte per row, bit 0 = leftmost pixel.  The font is
uppercase-only, so the table covers ASCII 32..95.

    python tools/gen_font.py
"""

import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)                 # .../firmware
ROOT = os.path.dirname(PROJ)                 # .../Cardputer_MIDI
FONTS = os.path.join(ROOT, "design", "fonts")
OUT = os.path.join(PROJ, "src", "font8.h")

CELL_W, CELL_H = 6, 8
FIRST, LAST = 32, 95


def rasterise(path):
    font = ImageFont.truetype(path, 8)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((0, -4), chr(code), font=font, fill=255)
        rows = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if img.getpixel((x, y)) > 128:
                    bits |= 1 << x
            rows.append(bits)
        glyphs.append(rows)
    return glyphs


def emit(name, glyphs, f):
    f.write(f"static const uint8_t {name}[{len(glyphs)}][{CELL_H}] = {{\n")
    for code, rows in zip(range(FIRST, LAST + 1), glyphs):
        hexes = ", ".join(f"0x{b:02X}" for b in rows)
        ch = chr(code).replace("\\", "\\\\").replace('"', '\\"')
        f.write(f"    {{ {hexes} }},  // '{ch}'\n")
    f.write("};\n\n")


def main():
    reg = rasterise(os.path.join(FONTS, "Silkscreen-Regular.ttf"))
    bold = rasterise(os.path.join(FONTS, "Silkscreen-Bold.ttf"))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_font.py - do not edit.\n")
        f.write("// Silkscreen 8 px, 6x8 cell, bit 0 = leftmost pixel.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define FONT_FIRST {FIRST}\n#define FONT_LAST {LAST}\n")
        f.write(f"#define FONT_W {CELL_W}\n#define FONT_H {CELL_H}\n\n")
        emit("FONT8", reg, f)
        emit("FONT8B", bold, f)

    # quick visual check
    for ch in "A8%_K":
        rows = reg[ord(ch) - FIRST]
        print(ch)
        for r in rows:
            print("".join("#" if r & (1 << x) else "." for x in range(CELL_W)))
        print()


if __name__ == "__main__":
    main()
